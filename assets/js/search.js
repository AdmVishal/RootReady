/* root_n_reels — search.js : lazy-loaded global search (MiniSearch + prebuilt JSON index).
   Index: /assets/search/index.json  (generated by tools/build.py). */
(function () {
  'use strict';
  var d = document, w = window, RR = w.RR || (w.RR = {});
  var ms = null, docs = [], syn = {}, cats = {}, ready = null, dlg = null, sel = -1, current = [], filter = 'all', typeF = '';
  var CAT_LABEL = { linux: 'Linux', unix: 'Unix', networking: 'Networking', infrastructure: 'Infra', devops: 'DevOps', security: 'Security', operations: 'Ops', interview: 'Interview', troubleshooting: 'Troubleshoot', cheat: 'Cheat sheets' };
  var CAT_COLOR = { linux: '#2F80ED', unix: '#D97706', networking: '#0891B2', infrastructure: '#64748B', devops: '#7C3AED', security: '#DC2626', operations: '#0A7A4B', interview: '#059669', troubleshooting: '#B45309', cheat: '#B45309' };
  var esc = function (s) { return String(s).replace(/[&<>"']/g, function (c) { return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]; }); };

  function loadScript(src) { return new Promise(function (res, rej) { if (w.MiniSearch) return res(); var s = d.createElement('script'); s.src = src; s.onload = res; s.onerror = rej; d.head.appendChild(s); }); }
  function load() {
    if (ready) return ready;
    ready = Promise.all([loadScript('/assets/js/vendor/minisearch.min.js'), fetch('/assets/search/index.json').then(function (r) { return r.json(); })]).then(function (r) {
      var data = r[1]; docs = data.docs; syn = data.syn || {}; cats = data.cats || {};
      ms = new w.MiniSearch({
        fields: ['t', 'h', 'tags', 'cmd', 'x'],
        storeFields: ['u', 'p', 't', 'h', 'c', 'k', 'l', 'x'],
        idField: 'id',
        searchOptions: { boost: { t: 5, tags: 4, cmd: 3, h: 2, x: 1 }, prefix: true, fuzzy: function (term) { return term.length > 4 ? 0.2 : false; } },
        /* keep command-ish tokens whole: systemctl, lvextend, /etc/fstab, ip6tables, read-only */
        tokenize: function (s) { return s.toLowerCase().split(/[\s,;:()\[\]{}"'`<>=|]+/).flatMap(function (tok) { tok = tok.replace(/^[.\-]+|[.\-]+$/g, ''); if (!tok) return []; var parts = tok.split(/[-_/.]+/).filter(Boolean); return parts.length > 1 ? [tok].concat(parts) : [tok]; }); }
      });
      ms.addAll(docs);
    });
    return ready;
  }
  function norm(q) { return q.trim().toLowerCase().replace(/\s+/g, ' '); }
  function expand(q) {
    var out = [], toks = q.split(' ');
    toks.forEach(function (t) { if (syn[t]) out = out.concat(syn[t]); });
    var two = q; if (syn[two]) out = out.concat(syn[two]);
    return out;
  }
  function run(q, opts) {
    q = norm(q); if (!q) return [];
    var f = function (r) { return (filter === 'all' || r.c === filter) && (!typeF || r.k === typeF); };
    var res = ms.search(q, { combineWith: 'AND', filter: f });
    var ex = expand(q);
    if (res.length < 6) {
      var res2 = ms.search((q + ' ' + ex.join(' ')).trim(), { combineWith: 'OR', filter: f });
      var seen = {}; res.forEach(function (r) { seen[r.id] = 1; });
      res2.forEach(function (r) { if (!seen[r.id]) { r.score *= 0.55; res.push(r); } });
    }
    var sym = /\b(full|slow|fail\w*|error|refused|read-only|not|won't|cannot|can't|down|stuck|hang|denied)\b/.test(q);
    var saved = (RR.bookmarks ? RR.bookmarks.list() : []).map(function (b) { return b.u; });
    res.forEach(function (r) {
      if (sym && r.k === 'troubleshoot') r.score *= 1.3;
      if (saved.indexOf(r.u) >= 0) r.score *= 1.2;
      if (r.k === 'article' && /^\/(linux|unix)\//.test(r.u)) r.score *= 1.1;
    });
    res.sort(function (a, b) { return b.score - a.score; });
    var terms = q.split(' ').concat(ex).filter(function (t) { return t.length > 1; });
    /* limit to 3 sections per page when not filtering to a single page */
    var per = {}, outl = [];
    res.forEach(function (r) { var k = r.p; per[k] = (per[k] || 0) + 1; if (per[k] <= 3 || (opts && opts.all)) outl.push(r); });
    outl.forEach(function (r) { r._terms = terms; });
    return outl.slice(0, (opts && opts.limit) || 40);
  }
  function snippet(x, terms) {
    x = x || ''; var lx = x.toLowerCase(), pos = -1;
    for (var i = 0; i < terms.length; i++) { var p = lx.indexOf(terms[i]); if (p >= 0 && (pos < 0 || p < pos)) pos = p; }
    var s = Math.max(0, (pos < 0 ? 0 : pos) - 60), e = Math.min(x.length, s + 170);
    var txt = (s > 0 ? '… ' : '') + x.slice(s, e) + (e < x.length ? ' …' : '');
    var h = esc(txt);
    terms.slice().sort(function (a, b) { return b.length - a.length; }).forEach(function (t) {
      try { h = h.replace(new RegExp('(' + esc(t).replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + ')', 'ig'), '<mark>$1</mark>'); } catch (e) {}
    });
    return h;
  }
  function hl(t, terms) {
    var h = esc(t);
    terms.forEach(function (x) { try { h = h.replace(new RegExp('(' + esc(x).replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + ')', 'ig'), '<mark>$1</mark>'); } catch (e) {} });
    return h;
  }
  var TAG = { qa: 'Q&A', troubleshoot: 'Fix', cheat: 'Cheat', article: '', lab: 'Lab' };
  function hitHtml(r, i) {
    var cat = r.c || 'linux';
    var tag = (TAG[r.k] || '') + (r.l ? (TAG[r.k] ? ' · ' : '') + r.l : '');
    return '<a class="hit" role="option" id="rr-hit-' + i + '" href="' + esc(r.u) + '" data-i="' + i + '" style="--cat:' + (CAT_COLOR[cat] || '#2F80ED') + '">' +
      '<div class="top"><span class="dot"></span><span>' + hl(r.t, r._terms) + '</span>' + (tag ? '<span class="tag">' + esc(tag) + '</span>' : '') + '</div>' +
      '<div class="path">' + esc(r.p) + (r.h ? ' › ' + esc(r.h) : '') + '</div>' +
      '<div class="snip">' + snippet(r.x, r._terms) + '</div></a>';
  }
  function recentSearches() { return RR.store ? RR.store.get('searches', []) : []; }
  function saveSearch(q) { if (!RR.store || q.length < 2) return; var l = recentSearches().filter(function (x) { return x !== q; }); l.unshift(q); RR.store.set('searches', l.slice(0, 8)); }

  var POPULAR = ['disk full', 'read-only file system', 'lvextend', 'selinux denied', 'multipath', 'high load', 'systemctl', 'zfs', 'boot rescue', 'ansible'];
  function emptyHtml() {
    var rs = recentSearches(), h = '';
    if (rs.length) h += '<div class="rr-shead">Recent searches</div><div style="padding:6px 16px 10px;display:flex;flex-wrap:wrap;gap:8px">' + rs.map(function (q) { return '<button type="button" class="rr-chip" data-q="' + esc(q) + '">' + esc(q) + '</button>'; }).join('') + '</div>';
    h += '<div class="rr-shead">Try</div><div style="padding:6px 16px 14px;display:flex;flex-wrap:wrap;gap:8px">' + POPULAR.map(function (q) { return '<button type="button" class="rr-chip" data-q="' + esc(q) + '">' + esc(q) + '</button>'; }).join('') + '</div>';
    return h;
  }
  function noResHtml(q) {
    var iss = 'https://github.com/AdmVishal/RootReady/issues/new?title=' + encodeURIComponent('Topic request: ' + q) + '&body=' + encodeURIComponent('I searched for "' + q + '" and found nothing useful.');
    return '<div class="rr-sempty"><h4>No match for “' + esc(q) + '”</h4><p>Try a shorter word, a command name, or an error message. Or <a href="/troubleshooting/">browse troubleshooting</a>, <a href="/cheat-sheets.html">cheat sheets</a> and <a href="/interview/">interview prep</a>.</p><p><a href="' + iss + '" target="_blank" rel="noopener">Request this topic →</a></p></div>';
  }

  function build() {
    dlg = d.createElement('dialog'); dlg.className = 'rr-search'; dlg.setAttribute('aria-label', 'Search root_n_reels');
    dlg.innerHTML =
      '<div class="rr-sbox"><svg class="rr-ico" viewBox="0 0 24 24" aria-hidden="true"><circle cx="11" cy="11" r="7"/><path d="m20 20-3.5-3.5"/></svg>' +
      '<input type="search" role="combobox" aria-expanded="true" aria-controls="rr-sres" aria-autocomplete="list" inputmode="search" enterkeyhint="search" autocomplete="off" autocapitalize="off" spellcheck="false" placeholder="Search commands, errors, topics…" aria-label="Search">' +
      '<button type="button" class="rr-act rr-sclose" data-close aria-label="Close search">Esc</button></div>' +
      '<div class="rr-sfilters" role="group" aria-label="Filter results"></div>' +
      '<div class="rr-sres" id="rr-sres" role="listbox" aria-label="Results" aria-live="polite"></div>' +
      '<div class="rr-sfoot"><span class="kbd-hint"><kbd>↑</kbd> <kbd>↓</kbd> navigate · <kbd>Enter</kbd> open · <kbd>Esc</kbd> close</span><span id="rr-scount"></span></div>';
    d.body.appendChild(dlg);
    var inp = dlg.querySelector('input'), box = dlg.querySelector('.rr-sres'), fl = dlg.querySelector('.rr-sfilters'), cnt = dlg.querySelector('#rr-scount');
    var FILTERS = [['all', 'All'], ['linux', 'Linux'], ['unix', 'Unix'], ['networking', 'Networking'], ['devops', 'DevOps'], ['security', 'Security'], ['infrastructure', 'Infra'], ['interview', 'Interview'], ['troubleshooting', 'Troubleshooting'], ['cheat', 'Cheat sheets']];
    fl.innerHTML = FILTERS.map(function (f) { return '<button type="button" class="rr-chip" data-f="' + f[0] + '" aria-pressed="' + (f[0] === 'all') + '">' + f[1] + '</button>'; }).join('') +
      '<button type="button" class="rr-chip" data-t="qa" aria-pressed="false">Q&amp;A only</button>';
    var timer;
    function render() {
      var q = inp.value;
      if (!norm(q)) { current = []; sel = -1; box.innerHTML = emptyHtml(); cnt.textContent = ''; return; }
      if (!ms) { box.innerHTML = '<div class="rr-sempty">Loading search index…</div>'; return; }
      current = run(q);
      sel = current.length ? 0 : -1;
      box.innerHTML = current.length ? current.map(hitHtml).join('') : noResHtml(q);
      cnt.textContent = current.length + ' result' + (current.length === 1 ? '' : 's');
      mark();
    }
    function mark() {
      var as = box.querySelectorAll('a.hit');
      as.forEach(function (a, i) { a.setAttribute('aria-selected', i === sel ? 'true' : 'false'); });
      if (sel >= 0 && as[sel]) { inp.setAttribute('aria-activedescendant', as[sel].id); as[sel].scrollIntoView({ block: 'nearest' }); }
    }
    inp.addEventListener('input', function () { clearTimeout(timer); timer = setTimeout(render, 60); });
    inp.addEventListener('keydown', function (e) {
      if (e.key === 'ArrowDown') { e.preventDefault(); if (current.length) { sel = (sel + 1) % current.length; mark(); } }
      else if (e.key === 'ArrowUp') { e.preventDefault(); if (current.length) { sel = (sel - 1 + current.length) % current.length; mark(); } }
      else if (e.key === 'Enter') { var a = box.querySelectorAll('a.hit')[sel]; saveSearch(norm(inp.value)); if (a) { e.preventDefault(); RR.track && RR.track('search:' + norm(inp.value)); location.href = a.getAttribute('href'); } }
    });
    box.addEventListener('click', function (e) {
      var c = e.target.closest('[data-q]'); if (c) { inp.value = c.dataset.q; render(); inp.focus(); return; }
      if (e.target.closest('a.hit')) saveSearch(norm(inp.value));
    });
    fl.addEventListener('click', function (e) {
      var b = e.target.closest('button'); if (!b) return;
      if (b.dataset.f) { filter = b.dataset.f; fl.querySelectorAll('[data-f]').forEach(function (x) { x.setAttribute('aria-pressed', x === b ? 'true' : 'false'); }); }
      if (b.dataset.t) { typeF = typeF === b.dataset.t ? '' : b.dataset.t; b.setAttribute('aria-pressed', typeF ? 'true' : 'false'); }
      render(); inp.focus();
    });
    dlg.addEventListener('click', function (e) { if (e.target === dlg || e.target.closest('[data-close]')) dlg.close(); });
    dlg.addEventListener('close', function () { if (history.state && history.state.rrs) history.back(); });
    w.addEventListener('popstate', function () { if (dlg.open) dlg.close(); });
    dlg._render = render; dlg._inp = inp;
  }
  function open(q) {
    if (!dlg) build();
    if (!dlg.open) { dlg.showModal(); try { history.pushState({ rrs: 1 }, ''); } catch (e) {} }
    dlg._inp.value = q || ''; dlg._render(); dlg._inp.focus();
    load().then(function () { dlg._render(); }).catch(function () { dlg.querySelector('.rr-sres').innerHTML = '<div class="rr-sempty">Search index could not be loaded. Check your connection and try again.</div>'; });
  }
  /* full results page helper */
  function page(el, q, filt) {
    load().then(function () {
      filter = filt || 'all';
      var r = run(q, { all: true, limit: 100 });
      el.innerHTML = r.length ? r.map(hitHtml).join('') : noResHtml(q);
      el.querySelectorAll('a.hit').forEach(function (a) { a.removeAttribute('role'); });
    });
  }
  w.RRSearch = { open: open, load: load, run: function (q, o) { return ms ? run(q, o) : []; }, page: page, ready: load };
})();
